     *
     * [swallow] drives the window into the snooze target — bottom-centre — and
     * then hides it **there**. Nothing ever moved it back, so ten minutes
     * later `applyVisibility` showed the window at the last coordinates
     * anything had written, which were the target's. The bubble did not
     * *travel* to the middle of the screen; it had been parked in the middle
     * of the screen, invisibly, since the moment it was snoozed.
     *
     * Confirmed against the owner's trace: the target sits at
     * `heightPixels - targetSize - 132dp`, horizontally centred, which is
     * exactly where the screenshot shows the bubble sitting over a web page.
     *
     * ## Why a remembered Y rather than a default one
     *
     * Because snapping to a fixed position would be a second bug wearing the
     * first one's clothes. The user drags this button to where they want it;
     * coming back from a snooze somewhere else is the same complaint with a
     * different coordinate. X does not need remembering — it is always one of
     * two edges and [parkedRight] already says which — but Y is wherever the
     * finger left it.
     *
     * Null until the bubble has settled once, which is only true before the
     * first drag; [restorePark] falls back to the same third-of-the-screen
     * that [addBubble] starts at.
     */
    private var restY: Int? = null

    /**
     * True from the moment a snooze drag is swallowed until the bubble is next
     * shown, and the reason [restY] survives the swallow.
     *
     * The swallow is driven by the same two springs as every other move, so
     * without this flag its frames would overwrite the resting position with
     * the target's on the way in — and the fix would restore the bubble to
     * precisely the place it is meant to be rescued from.
     */
    private var swallowed = false

    /** Re-show the bubble the moment a payment's quiet window expires. */
    private val unquiet = Runnable { applyVisibility() }

    // ── the physics ─────────────────────────────────────────────────────────
    //
    // `F-170`. **Everything the bubble does is a spring or a fling now, and
    // none of it has a duration.**
    //
    // > *"make it as beautiful and as seamless as the messenger bubble icon
    // > that comes and pops up … so it feels very native rather than too much
    // > sticky type experience"*
    //
    // That word — sticky — is an accurate description of what a fixed-duration
    // interpolator does. The old edge snap was
    // `ValueAnimator` + `OvershootInterpolator(1.1f)` + `duration = 260`, and
    // a duration is the problem: **a hard flick and a gentle nudge both took
    // 260 ms.** Throw the bubble across the screen and it crawls; push it a
    // centimetre and it lurches. The motion is not related to what the finger
    // did, so it reads as an animation being played *at* you rather than an
    // object you are holding.
    //
    // A `SpringAnimation` has no duration. It has a rest position, a
    // stiffness, a damping ratio and — the part that matters — a **start
    // velocity**, which is handed straight from the `VelocityTracker` that was
    // watching the finger. The same gesture that threw it is the thing that
    // decides how fast it arrives, so a flick lands hard and a nudge drifts.
    //
    // ## Where this came from
    //
    // Asked to go and look at how other people do this. The open-source chat
    // heads all reach for the same idea:
    //
    //   * flipkart-incubator/springy-heads — spring physics per head.
    //     **Checked again in prompt 44: unmaintained, and its README points at
    //     google/hover, which Google archived in January 2023.** Both of the
    //     best-known chat-head libraries are dead, which retrospectively
    //     justifies taking Android's own animators rather than one of them —
    //     adopting either would have been inheriting abandoned code. See
    //     `docs/39-FLOATING-OVERLAY-PRIOR-ART.md`
    //   * Crdzbird/floaty_chatheads — Facebook Rebound, the library Facebook
    //     wrote for chat heads before Android had its own
    //   * txusballesteros/bubbles-for-android, henrychuangtw/Android-ChatHead
    //
    // Rebound is what Messenger itself used. Android has since absorbed the
    // idea as `androidx.dynamicanimation` — same maths, ~50 KB, first-party,
    // no third-party animation runtime in an app whose selling point is that
    // it does not phone home. That is the dependency `bootstrap.sh` now
    // injects, and it is the first real use of the `F-161` mechanism.
    //
    // ## Why a `FloatPropertyCompat` and not `DynamicAnimation.X`
    //
    // The built-in `DynamicAnimation.X` / `.Y` animate a **View's** position
    // inside its parent. This bubble has no parent — it is its own window, and
    // it moves by mutating `WindowManager.LayoutParams` and calling
    // `updateViewLayout`. So the property is written by hand: the getter reads
    // the layout params, the setter writes them and pushes the window. The
    // spring does not know or care that it is driving a window rather than a
    // view, which is the whole point of the abstraction.

    /**
     * The window's left edge, as something a spring can pull on.
     *
     * `runCatching` because `updateViewLayout` throws if the window has
     * already been removed, and an animation outlives its view by up to a
     * frame — the service can be stopped mid-flight. A crash inside an
     * animation callback would take the whole app down for the sake of a
     * bubble that was on its way out anyway.
     */
    private val windowX = object : FloatPropertyCompat<View>("windowX") {
        override fun getValue(view: View): Float = (params?.x ?: 0).toFloat()
        override fun setValue(view: View, value: Float) {
            val lp = params ?: return
            lp.x = value.toInt()
            runCatching { windows.updateViewLayout(view, lp) }
        }
    }

    private val windowY = object : FloatPropertyCompat<View>("windowY") {
        override fun getValue(view: View): Float = (params?.y ?: 0).toFloat()
        override fun setValue(view: View, value: Float) {
            val lp = params ?: return
            lp.y = value.toInt()
            // `F-180`. Every settle, fling and re-anchor passes through here,
            // so this is the one place that sees the bubble come to rest —
            // except during a swallow, which is heading somewhere the bubble
            // is not meant to stay. See [restY].
            if (!swallowed) restY = lp.y
            runCatching { windows.updateViewLayout(view, lp) }
        }
    }

    /**
     * Held as fields, one per property, and **reused** rather than recreated.
     *
     * This is not a micro-optimisation, it is the interruption behaviour. A
     * running `SpringAnimation` handed a new `animateToFinalPosition` keeps
     * its current position *and its current velocity* and re-aims — so
     * grabbing the bubble mid-flight, or a second peek arriving during the
     * first one's settle, is continuous motion. Building a fresh animation
     * each time would start it from a standstill, which is the visible
     * stutter this whole change exists to remove.
     */
    private var slideX: SpringAnimation? = null
    private var settleY: SpringAnimation? = null
    private var glideY: FlingAnimation? = null
    private var popX: SpringAnimation? = null
    private var popY: SpringAnimation? = null

    private fun springFor(
        view: View,
        property: FloatPropertyCompat<View>,
        stiffness: Float,
        damping: Float,
    ): SpringAnimation = SpringAnimation(view, property).apply {
        // `setSpring(...)`, `setStiffness(...)` and `setDampingRatio(...)`
        // spelled out as calls rather than as Kotlin property assignments.
        // Every setter in `dynamicanimation` returns the object for chaining,
        // and **Kotlin only synthesises a property for a setter returning
        // void** — so `spring = …` and `stiffness = …` do not compile here.
        // They look like they should, which is why this note exists.
        setSpring(
            SpringForce().also {
                it.setStiffness(stiffness)
                it.setDampingRatio(damping)
            }
        )
    }

    /** Build every animation this bubble will ever need, once, on add. */
    private fun buildPhysics(view: View) {
        // LOW stiffness + LOW_BOUNCY: it travels a visible distance, so the
        // eye can follow it across, and it settles with one small overshoot
        // rather than the wobble MEDIUM_BOUNCY gives — a bubble that jiggles
        // twice after landing looks like a toy.
        slideX = springFor(
            view, windowX,
            SpringForce.STIFFNESS_LOW,
            SpringForce.DAMPING_RATIO_LOW_BOUNCY,
        )
        // NO_BOUNCY vertically. Horizontal overshoot reads as landing against
        // the edge; vertical overshoot reads as the bubble having been
        // *dropped*, because there is no edge there to land on.
        settleY = springFor(
            view, windowY,
            SpringForce.STIFFNESS_LOW,
            SpringForce.DAMPING_RATIO_NO_BOUNCY,
        )
        // The press, and the pop-in. MEDIUM_BOUNCY is right for scale in a way
        // it is not for position: a button that squashes and springs back with
        // a little life is the single clearest "this is a real control"
        // signal, and it is what makes the Messenger head feel alive.
        popX = springFor(
            view, DynamicAnimation.SCALE_X,
            SpringForce.STIFFNESS_MEDIUM,
            SpringForce.DAMPING_RATIO_MEDIUM_BOUNCY,
        )
        popY = springFor(
            view, DynamicAnimation.SCALE_Y,
            SpringForce.STIFFNESS_MEDIUM,
            SpringForce.DAMPING_RATIO_MEDIUM_BOUNCY,
        )
    }

    // ── the snooze target ───────────────────────────────────────────────────
    //
    // `F-173`. **Drag the bubble onto it and SWIP goes away for ten minutes.**
    //
    // > *"we need snoozing mechanism where in i drag and drop the launcher
    // > icon to the center … it should snooze for 10mins by default and if I
    // > shake the phone it should be back"*
    //
    // `docs/32` §4 has specified this since the beginning — *"a delete target
    // that appears at the bottom on drag"*, Messenger's model — and it was
    // still on the not-built list a round ago. This is it, doing snooze rather
    // than delete, because SWIP's bubble is not a conversation you close: it
    // is a tool you want back.
    //
    // ## What it replaces, and why the old gesture is deleted rather than kept
    //
    // A long-press. Which nobody discovers, and which is what the owner is
    // describing as *"on holding the launcher icon it glitches and is not
    // smooth animating"* — accurately, because a long-press fired **under a
    // finger that might still be about to drag**, and its handler then ran a
    // text peek, a re-anchor spring and a scale kick at once, on a view whose
    // press spring was still settling. Four animations, one view, one frame.
    //
    // A drag target has none of that shape. The gesture is already a drag, so
    // nothing has to guess what it will become; the animation is the bubble
    // being pulled into the target, which is one spring; and it is visible
    // from the moment you start, so it teaches itself.
    //
    // ## Why bottom-centre and not the middle of the screen
    //
    // The owner said "the center", and horizontally that is exactly what this
    // is. Vertically it sits above the bottom edge rather than at the true
    // centre, and that is a correction worth stating rather than making
    // quietly: **the middle of the screen is where the bubble passes through
    // on almost every ordinary drag.** A target there would swallow the bubble
    // every time someone moved it from one side to the other, which is the
    // most common thing they do with it. Every chat-head implementation puts
    // the target near the bottom for this reason, and it is also where a thumb
    // already is.

    // ── the fan ─────────────────────────────────────────────────────────────
    //
    // `F-185`. **What a tap does now.**
    //
    // > *"Once you click the launcher icon, it is not bouncy enough. It opens
    // > as something called 'scanning.' It's actually not scanning, right?…
    // > if you click on the launcher icon, it gives you two options: 1. the QR
    // > 2. the POS"*
    //
    // Both halves of that were right, and they were one mechanism.
    //
    // A tap used to call `peek()`, which makes the bubble **expand into a
    // pill** carrying the word *Scanning…*. That is where the rounded
    // rectangle the owner reported came from — the circle is a circle only
    // while the label is `GONE`, because `swip_bubble_bg` is a rectangle whose
    // corner radius is half the height, and a pill is what that becomes the
    // moment the view is wider than it is tall.
    //
    // And the word was a lie. Nothing was scanning: the hovering window had
    // not started, its Flutter engine had not started, and the camera was half
    // a second away. The label existed to cover that half second, which is a
    // reasonable thing to want and a bad thing to lie about.
    //
    // So the tap opens a fan instead. The bubble's own glyph becomes a cross,
    // two discs spring out above it, and the delay is now covered by a
    // deliberate choice rather than by a caption. It also answers a question
    // the old design could not: **SWIP has two capture vectors and the bubble
    // only ever offered one of them.**
    //
    // ## Why the items are their own windows
    //
    // The same reason the snooze target is. The bubble's window is
    // `WRAP_CONTENT` and sized to the bubble; growing it to hold a menu would
    // change the thing the drag maths, the edge snapping and `BubblePark` all
    // measure. Separate windows leave every one of those untouched.
    //
    // ## Why there is no full-screen scrim
    //
    // A FAB menu normally dims everything and closes on an outside tap. Doing
    // that here means a full-screen **touchable** overlay over somebody else's
    // app, which is exactly the "in the way" that `docs/32` §4 rules out. The
    // fan closes on: choosing an item, pressing the cross, starting a drag,
    // the bubble being hidden for any reason, or [FAN_TIMEOUT_MS] of nothing.

    private var fanViews: List<View> = emptyList()
    private var fanOpen = false

    /** Closes an unattended fan, so it is never found open later. */
    private val fanTimeout = Runnable { closeFan() }

    private fun toggleFan() {
        if (fanOpen) closeFan() else openFan()
    }

    /**
     * Spring two discs out of the bubble.
     *
     * Upwards when there is room, downwards when the bubble is parked near the
     * top. The check is against the **items' own extent**, not the bubble's:
     * a fan that opens off the top of the screen is a menu with no items in
     * it, and on a window with `FLAG_LAYOUT_NO_LIMITS` nothing stops it.
     */
    private fun openFan() {
        val host = bubble ?: return
        val lp = params ?: return
        if (fanOpen) return
        fanOpen = true

        val gap = dp(FAN_GAP_DP)
        val size = dp(56f)
        val screenHeight = resources.displayMetrics.heightPixels
        // Room for two items plus a margin, measured from the bubble's top.
        val up = lp.y - 2 * gap >= dp(8f)
        val step = if (up) -gap else gap
        val originY = if (up) lp.y else lp.y + (host.height - size)

        val items = listOf(
            R.drawable.swip_fan_qr to getString(R.string.swip_fan_qr),
            R.drawable.swip_fan_pos to getString(R.string.swip_fan_pos),
        )

        val built = mutableListOf<View>()
        items.forEachIndexed { i, (icon, label) ->
            val view = buildFanItem(icon, label) {
                closeFan()
                if (i == 0) openScanner() else openTapScreen()
            }
            val itemLp = WindowManager.LayoutParams(
                size,
                size,
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O)
                    WindowManager.LayoutParams.TYPE_APPLICATION_OVERLAY
                else
                    @Suppress("DEPRECATION")
                    WindowManager.LayoutParams.TYPE_PHONE,
                // Touchable, unlike the snooze target — these are buttons.
                // NOT_FOCUSABLE still, or the keyboard closes in whatever app
                // the user is typing in.
                WindowManager.LayoutParams.FLAG_NOT_FOCUSABLE or
                    WindowManager.LayoutParams.FLAG_LAYOUT_NO_LIMITS,
                PixelFormat.TRANSLUCENT,
            ).apply {
                gravity = Gravity.TOP or Gravity.START
                x = lp.x + (host.width - size) / 2
                // `coerceIn` throws when its maximum is below its minimum,
                // and both bounds here come from a live screen measurement —
                // the hazard `BubblePark` exists to contain. `coerceAtLeast`
                // first makes the range provably non-empty.
                y = (originY + step * (i + 1)).coerceIn(
                    dp(8f),
                    (screenHeight - size - dp(8f)).coerceAtLeast(dp(8f)),
                )
            }

            runCatching { windows.addView(view, itemLp) }
                .onSuccess {
                    built += view
                    // Staggered, because two discs arriving on the same frame
                    // read as one wide thing appearing rather than as a menu
                    // unfolding. 45 ms is about one and a half frames.
                    main.postDelayed({
                        if (!fanOpen) return@postDelayed
                        springFor(view, DynamicAnimation.SCALE_X,
                            SpringForce.STIFFNESS_MEDIUM,
                            SpringForce.DAMPING_RATIO_MEDIUM_BOUNCY)
                            .animateToFinalPosition(1f)
                        springFor(view, DynamicAnimation.SCALE_Y,
                            SpringForce.STIFFNESS_MEDIUM,
                            SpringForce.DAMPING_RATIO_MEDIUM_BOUNCY)
                            .animateToFinalPosition(1f)
                        view.animate().alpha(1f).setDuration(120).start()
                    }, FAN_STAGGER_MS * i)
                }
        }

        fanViews = built
        if (built.isEmpty()) {
            // Every `addView` failed, which means the overlay permission went
            // away underneath us. Do not leave `fanOpen` true — the next tap
            // would try to close a fan that was never on screen and do nothing
            // at all, which is the worst of the three outcomes.
            fanOpen = false
            return
        }

        glyph?.setImageResource(R.drawable.swip_fan_close)
        // The cross arrives with a quarter turn, so the change is motion
        // rather than a swap the eye has to notice after the fact.
        glyph?.animate()?.rotationBy(90f)?.setDuration(180)?.start()
        runCatching {
            host.performHapticFeedback(HapticFeedbackConstants.CONTEXT_CLICK)
        }
        main.removeCallbacks(fanTimeout)
        main.postDelayed(fanTimeout, FAN_TIMEOUT_MS)
        BubbleTrace.log(this, "fan.open", "up" to up, "items" to built.size)
    }

    /** Take the fan away. Safe to call when there is no fan. */
    private fun closeFan() {
        main.removeCallbacks(fanTimeout)
        if (!fanOpen) return
        fanOpen = false

        for (view in fanViews) {
            // Faded and removed in the callback rather than removed outright:
            // `removeView` is immediate, so dropping the windows on this frame
            // makes two discs vanish rather than leave.
            view.animate()
                .alpha(0f).scaleX(0.4f).scaleY(0.4f)
                .setDuration(130)
                .withEndAction { runCatching { windows.removeView(view) } }
                .start()
        }
        fanViews = emptyList()

        glyph?.setImageResource(R.drawable.swip_bubble_mark)
        glyph?.animate()?.rotationBy(-90f)?.setDuration(180)?.start()
        BubbleTrace.log(this, "fan.close")
    }

    /** One disc in the fan: the bubble's own ground, with a different mark. */
    private fun buildFanItem(
        icon: Int,
        label: String,
        onTap: () -> Unit,
    ): View {
        val size = dp(56f)
        val disc = dp(38f)
        val pad = (size - disc) / 2

        val mark = ImageView(this).apply {
            setBackgroundResource(R.drawable.swip_bubble_disc)
            setImageResource(icon)
            setPadding(dp(7f), dp(7f), dp(7f), dp(7f))
            layoutParams = LinearLayout.LayoutParams(disc, disc)
        }

        return LinearLayout(this).apply {
            orientation = LinearLayout.HORIZONTAL
            gravity = Gravity.CENTER
            minimumWidth = size
            minimumHeight = size
            setPadding(pad, pad, pad, pad)
            setBackgroundResource(R.drawable.swip_bubble_bg)
            alpha = 0f
            // Starts small so the spring has somewhere to come from. Set here
            // rather than after `addView`, or the first frame is full size and
            // the pop reads as a flash.
            scaleX = 0.4f
            scaleY = 0.4f
            addView(mark)
            isClickable = true
            contentDescription = label
            setOnClickListener {
                runCatching {
                    it.performHapticFeedback(HapticFeedbackConstants.CONTEXT_CLICK)
                }
                onTap()
            }
        }
    }

    /**
     * `F-185`. Bring the real app forward at the POS screen.
     *
     * NFC cannot be read from the hovering window — that engine has no
     * `MainActivity` channel, and `CLAUDE.md` records what an unanswered
     * `MethodChannel` does to a screen. It is also the honest thing for the
     * user: tapping a terminal means holding the phone against it, which is
     * not something to do through a card floating over somebody else's app.
     *
     * `SINGLE_TOP` so a running SWIP is reused rather than stacked, which is
     * also what delivers the extra to `onNewIntent`.
     */
    private fun openTapScreen() {
        BubbleTrace.log(this, "tap.openPos")
        runCatching {
            startActivity(
                Intent(this, MainActivity::class.java).apply {
                    addFlags(
                        Intent.FLAG_ACTIVITY_NEW_TASK or
                            Intent.FLAG_ACTIVITY_SINGLE_TOP
                    )
                    putExtra(MainActivity.EXTRA_OPEN_TAP, true)
                }
            )
        }
    }

    private var target: View? = null
    private var targetParams: WindowManager.LayoutParams? = null

    /** Whether the bubble is currently close enough to be swallowed. */
    private var targetArmed = false

    private var targetScaleX: SpringAnimation? = null
    private var targetScaleY: SpringAnimation? = null

    /** Radius, from the target's centre, within which a drop counts. */
    private val targetGrab: Int get() = dp(64f)

    /**
     * The target's diameter, in one place.
     *
     * Four methods need it — building it, positioning its window, measuring
     * the distance to it, and aiming the swallow. It was written out four
     * times for about ten minutes, which was long enough for
     * `check_wiring.py`'s bubble-radius rule to match **this** `val size`
     * instead of the bubble's and fail the build demanding a 36 dp corner.
     *
     * A repeated literal is not only a thing that can drift. It is a thing
     * other tools can mistake for something else.
     */
    private val targetSize: Int get() = dp(72f)

    private fun buildTarget(): View = ImageView(this).apply {
        setBackgroundResource(R.drawable.swip_snooze_target)
        setImageResource(R.drawable.swip_snooze_mark)
        val pad = dp(22f)
        setPadding(pad, pad, pad, pad)
        // No `layoutParams` here. This view is added straight to the
        // WindowManager, so its size comes from the `WindowManager.LayoutParams`
        // in [showTarget] and anything set here is replaced by `addView`.
        contentDescription = getString(R.string.swip_bubble_snooze_target)
        // Starts invisible-small; [showTarget] springs it up. Set here
        // rather than there so the very first frame after `addView` is
        // already the small one — assigning after the window is added shows
        // one frame at full size, which reads as a flash.
        scaleX = 0.4f
        scaleY = 0.4f
        alpha = 0f
    }

    /**
     * Put the target on screen. Called when a drag is recognised, **not** on
     * touch-down: a tap would otherwise flash a snooze target at the user for
     * one frame every time they opened the scanner.
     */
    private fun showTarget() {
        if (target != null) return

        val view = buildTarget()
        val size = targetSize
        val lp = WindowManager.LayoutParams(
            size,
            size,
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O)
                WindowManager.LayoutParams.TYPE_APPLICATION_OVERLAY
            else
                @Suppress("DEPRECATION")
                WindowManager.LayoutParams.TYPE_PHONE,
            // NOT_TOUCHABLE as well as NOT_FOCUSABLE, which the bubble's window
            // does not have and this one must: the finger dragging the bubble
            // is going to pass over these pixels, and a window that accepts
            // touches would steal the gesture from the view being dragged
            // halfway through it.
            WindowManager.LayoutParams.FLAG_NOT_FOCUSABLE or
                WindowManager.LayoutParams.FLAG_NOT_TOUCHABLE or
                WindowManager.LayoutParams.FLAG_LAYOUT_NO_LIMITS,
            PixelFormat.TRANSLUCENT,
        ).apply {
            gravity = Gravity.TOP or Gravity.START
            x = (resources.displayMetrics.widthPixels - size) / 2
            y = resources.displayMetrics.heightPixels - size - dp(132f)
        }

        runCatching { windows.addView(view, lp) }
            .onSuccess {
                target = view
                targetParams = lp
                targetArmed = false
                targetScaleX = springFor(
                    view, DynamicAnimation.SCALE_X,
                    SpringForce.STIFFNESS_MEDIUM,
                    SpringForce.DAMPING_RATIO_LOW_BOUNCY,
                )
                targetScaleY = springFor(
                    view, DynamicAnimation.SCALE_Y,
                    SpringForce.STIFFNESS_MEDIUM,
                    SpringForce.DAMPING_RATIO_LOW_BOUNCY,
                )
                targetScaleX?.animateToFinalPosition(1f)
                targetScaleY?.animateToFinalPosition(1f)
                view.animate().alpha(1f).setDuration(140).start()
            }
    }

    private fun hideTarget() {
        val view = target ?: return
        target = null
        targetParams = null
        targetArmed = false
        runCatching { targetScaleX?.cancel(); targetScaleY?.cancel() }
        targetScaleX = null
        targetScaleY = null
        // Faded out first and removed in the callback, because
        // `removeView` is immediate — dropping the window on the same frame
        // makes the target vanish rather than leave.
        view.animate().alpha(0f).scaleX(0.5f).scaleY(0.5f)
            .setDuration(140)
            .withEndAction { runCatching { windows.removeView(view) } }
            .start()
    }

    /**
     * True when the bubble's centre is within [targetGrab] of the target's.
     *
     * Distance from the **centres**, not rectangle intersection: a 56 dp
     * bubble and a 72 dp target touch corners long before the gesture looks
     * like a drop, so intersection arms far too eagerly and the user cannot
     * drag past the bottom of the screen without snoozing.
     */
    private fun overTarget(bubble: View, lp: WindowManager.LayoutParams): Boolean {
        val tp = targetParams ?: return false
        val size = targetSize
        val dx = (lp.x + bubble.width / 2f) - (tp.x + size / 2f)
        val dy = (lp.y + bubble.height / 2f) - (tp.y + size / 2f)
        return dx * dx + dy * dy <= targetGrab.toFloat() * targetGrab
    }

    /** Grow the target and buzz once when the bubble comes into range. */
    private fun updateTarget(bubble: View, lp: WindowManager.LayoutParams) {
        val view = target ?: return
        val armed = overTarget(bubble, lp)
        if (armed == targetArmed) return
        targetArmed = armed

        targetScaleX?.animateToFinalPosition(if (armed) 1.3f else 1f)
        targetScaleY?.animateToFinalPosition(if (armed) 1.3f else 1f)
        // The bubble shrinks towards the target as well, which is what makes
        // the pair read as one being drawn into the other rather than two
        // things overlapping.
        scaleTo(if (armed) 0.7f else 0.88f)

        // `performHapticFeedback` rather than `Vibrator`: it needs no
        // permission, it honours the user's system haptics setting, and on a
        // drag target the buzz IS the affordance — it is how you know the drop
        // will land without looking away from what you are dragging.
        runCatching {
            if (armed) {
                view.performHapticFeedback(HapticFeedbackConstants.LONG_PRESS)
            }
        }
    }

    /**
     * The drop. Pull the bubble the rest of the way in, shrink it to nothing,
     * then snooze.
     *
     * [goodbyeUntil] is claimed before the snooze is written, for the reason
     * recorded on that field: writing it nudges the receiver, and the receiver
     * hides the bubble. Without the grace this animation would be cut off on
     * its first frame — which is exactly the bug `F-170` found in the gesture
     * this one replaces.
     */
    private fun swallow(bubble: View, centre: Pair<Int, Int>?, undoY: Int) {
        // `F-184`. **Before the springs, and before `swallowed` guards the
        // recorder.** The drag that ended here has already walked [restY] down
        // onto the target one `ACTION_MOVE` at a time, so the value that needs
        // restoring in ten minutes is the one from touch-down, not the one the
        // gesture left behind. Assigning it here rather than suppressing the
        // recorder during a drag keeps repositioning working: that gesture is
        // supposed to move the resting place, and this one is not.
        restY = undoY
        goodbyeUntil = System.currentTimeMillis() + SWALLOW_MS
        // `F-180`. Claimed **before** the springs below are aimed, because
        // they drive the same property the resting position is recorded from.
        // Set it after, and the first frame of the swallow would already have
        // overwritten the place the bubble is supposed to come back to.
        swallowed = true

        // [centre] is passed in rather than read from `targetParams`, and that
        // is a bug fix rather than a style. The touch handler hides the target
        // the moment the finger lifts — it has to, or a gesture that ends
        // anywhere leaves an overlay window on screen — and `hideTarget` nulls
        // `targetParams`. Reading it here would therefore always find null, so
        // the bubble would shrink where it was dropped instead of being pulled
        // in, and the one animation this whole gesture exists to show would
        // never have played.
        if (centre != null) {
            slideX?.apply {
                cancel()
                setStartVelocity(0f)
                animateToFinalPosition(centre.first - bubble.width / 2f)
            }
            settleY?.apply {
                cancel()
                setStartVelocity(0f)
                animateToFinalPosition(centre.second - bubble.height / 2f)
            }
        }
        scaleTo(0f)

        snoozeBriefly(this)

        // A system toast, which is what the owner's Wispr Flow screenshot
        // shows — a pill above the keyboard saying where the button went and
        // how to get it back. It has to be a toast rather than something drawn
        // in the bubble, because the bubble is the thing that just left.
        runCatching {
            Toast.makeText(
                this,
                getString(R.string.swip_bubble_snoozed_toast),
                Toast.LENGTH_LONG,
            ).show()
        }
        applyVisibility()
    }

    // ── shake to bring it back ──────────────────────────────────────────────
    //
    // `F-173`. Armed **only while snoozed**, which is the whole reason this is
    // acceptable at all: a floating button that listens to the accelerometer
    // all day is a battery complaint waiting to be written, and one that
    // listens for the ten minutes it is deliberately hiding is not.
    //
    // The decision of what counts as a shake lives in [ShakeDetector], which
    // has no Android in it and is unit-tested on the JVM — see
    // `ShakeDetectorTest.kt`. That split exists because both ways this can be
    // wrong are silent: too sensitive and the bubble returns while the user is
    // walking, undoing something they asked for; too dull and shaking does
    // nothing and they cannot tell whether they shook it wrong.

    private val shake = ShakeDetector()
    private var sensors: SensorManager? = null
    private var listening = false

    private val shakeListener = object : SensorEventListener {
        override fun onAccuracyChanged(sensor: Sensor?, accuracy: Int) = Unit

        override fun onSensorChanged(event: SensorEvent?) {
            val v = event?.values ?: return
            if (v.size < 3) return
            // `elapsedRealtime`, not `currentTimeMillis`: the wall clock jumps
            // when the network corrects it, and a backwards jump mid-gesture
            // would park the detector's window in the future.
            if (!shake.onSample(v[0], v[1], v[2], SystemClock.elapsedRealtime())) return
            if (snoozedUntil(this@SwipBubbleService) <= 0L) return
            wake(this@SwipBubbleService, from = "shake")
            applyVisibility()
        }
    }

    private fun listenForShake(on: Boolean) {
        if (on == listening) return
        listening = on

        if (!on) {
            runCatching { sensors?.unregisterListener(shakeListener) }
            return
        }

        val manager = sensors
            ?: (getSystemService(Context.SENSOR_SERVICE) as? SensorManager)
                ?.also { sensors = it }
            ?: return
        val accelerometer = manager.getDefaultSensor(Sensor.TYPE_ACCELEROMETER)
        if (accelerometer == null) {
            // No accelerometer at all — rare, but a tablet or an emulator. The
            // snooze still ends on its own timer, so the feature degrades to
            // "wait ten minutes" rather than breaking.
            listening = false
            return
        }
        shake.reset()
        // `SENSOR_DELAY_UI` is about 60 ms. `NORMAL` (200 ms) is cheaper and
        // too slow: a wrist reverses in roughly 150-250 ms, so at 200 ms the
        // sampling aliases against the gesture and a genuine shake can miss.
        runCatching {
            manager.registerListener(
                shakeListener, accelerometer, SensorManager.SENSOR_DELAY_UI)
        }
    }

    /** Stop everything mid-flight. Called on touch-down and on removal. */
    private fun cancelMotion() {
        runCatching { slideX?.cancel() }
        runCatching { settleY?.cancel() }
        runCatching { glideY?.cancel() }
        glideY = null
    }

    /**
     * Spring both scales to [to]. The press, the release and the pop-in.
     *
     * The explicit zero matters because a `DynamicAnimation` **keeps its start
     * velocity after being cancelled** — `endAnimationInternal` clears the
     * start *value* and leaves the velocity alone. So a press arriving after a
     * cancelled [kickScale] would inherit that kick and shoot past its target.
     *
     * It costs nothing when the spring is already running: `SpringAnimation`
     * reads the start velocity only at `start()`, and
     * `animateToFinalPosition` on a running spring just re-aims it, keeping
     * the motion it already has. Zeroing here is therefore "clean start when
     * stopped, continuous when moving", which is what both callers want.
     */
    private fun scaleTo(to: Float) {
        popX?.apply { setStartVelocity(0f); animateToFinalPosition(to) }
        popY?.apply { setStartVelocity(0f); animateToFinalPosition(to) }
    }

    /**
     * Shove the bubble outwards and let it come back by itself.
     *
     * A spring whose rest position is already where it is, handed a velocity,
     * overshoots and settles — which is a bulge with no duration, no end
     * callback and nothing to cancel — which is why the chained version that
     * used to live in the pill's peek had to go.
     */
    private fun kickScale(velocity: Float) {
        // `cancel()` first, and this is the one place it is right to. A start
        // velocity is only read at `start()`, so kicking a spring that is
        // already running — a peek during the pop-in, say — would be silently
        // ignored and the bubble would not acknowledge the tap at all. Here
        // the bump IS the feedback, so it has to be guaranteed rather than
        // merged.
        for (spring in listOfNotNull(popX, popY)) {
            spring.cancel()
            spring.setStartVelocity(velocity)
            spring.animateToFinalPosition(1f)
        }
    }

    private val systemEvents = object : BroadcastReceiver() {
        override fun onReceive(context: Context?, intent: Intent?) {
            when (intent?.action) {
                Intent.ACTION_SCREEN_OFF -> screenOff = true
                Intent.ACTION_SCREEN_ON, Intent.ACTION_USER_PRESENT ->
                    screenOff = false
            }
            BubbleTrace.log(this@SwipBubbleService, "broadcast",
                "action" to (intent?.action?.substringAfterLast('.') ?: "null"))
            // Everything else — foreground, payment quiet — is read from the
            // companion rather than carried on the intent, so this handler has
            // nothing to get wrong and a lost broadcast costs nothing.
            applyVisibility()
        }
    }

    override fun onBind(intent: Intent?): IBinder? = null

    override fun onCreate() {
        super.onCreate()
        BubbleTrace.log(this, "service.create")
        windows = getSystemService(Context.WINDOW_SERVICE) as WindowManager

        // Seeded, not assumed. A service started while the screen is off (a
        // boot that finishes in a pocket, for instance) must not put a bubble
        // on a display nobody is looking at.
        screenOff = runCatching {
            !(getSystemService(Context.POWER_SERVICE) as android.os.PowerManager)
                .isInteractive
        }.getOrDefault(false)

        startInForeground()

        val filter = IntentFilter().apply {
            addAction(Intent.ACTION_SCREEN_OFF)
            addAction(Intent.ACTION_SCREEN_ON)
            addAction(Intent.ACTION_USER_PRESENT)
            addAction(ACTION_RE_EVALUATE)
        }
        // The three SWIP actions are strictly in-process; the screen ones are
        // system broadcasts. `RECEIVER_NOT_EXPORTED` is correct for both here
        // because protected system broadcasts are delivered regardless.
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            registerReceiver(systemEvents, filter, Context.RECEIVER_NOT_EXPORTED)
        } else {
            @Suppress("UnspecifiedRegisterReceiverFlag")
            registerReceiver(systemEvents, filter)
        }
    }

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        BubbleTrace.log(this, "service.start",
            "action" to (intent?.action ?: "null"),
            // A redelivered start with a null intent is Android restarting the
            // service after killing it. That is a different story from the
            // user turning something on, and telling the two apart is most of
            // the point of this trace.
            "restarted" to (intent == null))

        if (intent?.action == ACTION_STOP) {
            // The notification's "Turn off". It has to write the preference
            // too, not just stop the service - otherwise `restoreIfWanted`
            // would put the bubble straight back the next time SWIP opened,
            // and the user would have dismissed it for nothing.
            stop(this)
            stopSelf()
            return START_NOT_STICKY
        }

        if (intent?.action == ACTION_SNOOZE_HOUR) {
            // Snooze, not stop: the service stays up so it can come back on
            // its own. Stopping would need something to restart it, and the
            // only thing that does is opening SWIP.
            snooze(this, System.currentTimeMillis() + ONE_HOUR_MS,
                from = "shadeAction")
            applyVisibility()
            return START_STICKY
        }

        // Without the permission there is nothing to draw and never will be.
        // Stopping rather than sitting there as a dead notification is the
        // honest behaviour.
        if (!canOverlay(this)) {
            stopSelf()
            return START_NOT_STICKY
        }

        if (bubble == null) addBubble()
        running = true
        applyVisibility()
        // START_STICKY: if Android kills the service under memory pressure the
        // user's answer to "should the bubble be there" has not changed, so it
        // should come back.
        return START_STICKY
    }

    override fun onDestroy() {
        // Before `running` is cleared, so the line records the state it died
        // in rather than the state it was being put into.
        BubbleTrace.log(this, "service.destroy", "wanted" to isWanted(this))
        running = false
        // Before anything else: an accelerometer listener that outlives its
        // service is a leak the system logs and nobody reads.
        listenForShake(false)
        hideTarget()
        main.removeCallbacks(unquiet)
        // `F-185`. The fan is windows of its own, so it has to go before the
        // service does or two discs outlive the thing that owns them.
        main.removeCallbacks(fanTimeout)
        closeFan()
        runCatching { unregisterReceiver(systemEvents) }
        removeBubble()
        super.onDestroy()
    }

    // ── the window ──────────────────────────────────────────────────────────

    private fun dp(value: Float): Int = TypedValue.applyDimension(
        TypedValue.COMPLEX_UNIT_DIP, value, resources.displayMetrics
    ).toInt()

    private fun addBubble() {
        val view = buildBubble()

        val lp = WindowManager.LayoutParams(
            WindowManager.LayoutParams.WRAP_CONTENT,
            WindowManager.LayoutParams.WRAP_CONTENT,
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O)
                WindowManager.LayoutParams.TYPE_APPLICATION_OVERLAY
            else
                @Suppress("DEPRECATION")
                WindowManager.LayoutParams.TYPE_PHONE,
            // NOT_FOCUSABLE is load-bearing: without it the bubble takes key
            // input from whatever is underneath, so the keyboard closes in the
            // app the user is actually typing in.
            WindowManager.LayoutParams.FLAG_NOT_FOCUSABLE or
                WindowManager.LayoutParams.FLAG_LAYOUT_NO_LIMITS,
            PixelFormat.TRANSLUCENT,
        ).apply {
            gravity = Gravity.TOP or Gravity.START
            // `F-170`. The 8 dp margin, not 0. Every later rest position is
            // `margin` or `screenWidth - width - margin`, so starting flush
            // against the glass meant the very first drag ended with the
            // bubble sitting 8 dp further in than where it had begun, for no
            // reason the user could see.
            x = dp(8f)
            // Roughly a third down the screen: clear of the status bar, clear
            // of the thumb's resting place, and out of the way of the bottom
            // sheets most apps put their primary action in.
            y = resources.displayMetrics.heightPixels / 3
        }

        runCatching { windows.addView(view, lp) }
            .onFailure {
                BubbleTrace.log(this, "bubble.addFailed",
                    "error" to it.javaClass.simpleName)
            }
            .onSuccess {
                BubbleTrace.log(this, "bubble.added", "x" to lp.x, "y" to lp.y)
                bubble = view
                params = lp
                // Ordered after the assignment: `windowX`/`windowY` read
                // `params`, so a spring built before it is set would take its
                // start position from a null and begin at zero.
                buildPhysics(view)
            }
    }

    private fun removeBubble() {
        closeFan()
        BubbleTrace.log(this, "bubble.removed")
        cancelMotion()
        // Reset, or a service that is stopped and started again builds a fresh
        // view while `show` still believes the old one was on screen — and the
        // guard there would then skip the pop-in for the one appearance that
        // most needs it.
        wasVisible = false
        slideX = null
        settleY = null
        popX = null
        popY = null
        bubble?.let { v -> runCatching { windows.removeView(v) } }
        bubble = null
        params = null
    }

    /**
     * Any reason to be hidden wins, and every reason is **read here** rather
     * than remembered from an event that may never have arrived.
     *
     * That is the whole fix for the bubble that would not appear: this method
     * is called on every start, every system broadcast and every nudge, and
     * each time it asks what is true now.
     */
    private fun applyVisibility() {
        val now = System.currentTimeMillis()
        val quiet = now < quietUntil
        // `F-167`. Read from storage rather than a field, so a snooze survives
        // the process being reclaimed and the phone restarting — which are the
        // two things most likely to happen during one.
        val asleep = snoozedUntil(this)
        val hidden = screenOff || quiet || appInForeground || asleep > 0L
        traceVisibility(hidden, screenOff, quiet, appInForeground, asleep)
        show(!hidden)

        // `F-173`. The accelerometer is registered here and nowhere else, so
        // "listening" and "snoozed" cannot drift apart: this method already
        // runs on every start, every system broadcast and every nudge, and it
        // already reads the snooze from storage. Anywhere else would be a
        // second source of truth for the same fact.
        listenForShake(asleep > 0L)

        // Re-check when whichever timer expires first; nothing else will wake
        // us. A snooze can be hours away, and `postDelayed` holds no wakelock,
        // so this fires late rather than never — acceptable for a button whose
        // whole job at that moment is to be absent.
        main.removeCallbacks(unquiet)
        val next = listOfNotNull(
            if (quiet) quietUntil else null,
            if (asleep > 0L) asleep else null,
        ).minOrNull()
        if (next != null) main.postDelayed(unquiet, next - now + 250L)
    }

    /**
     * `F-176`. The line that answers *"why did the button go?"*.
     *
     * Four independent facts decide it, and from outside all four look the
     * same — the bubble is simply not there. So the four are written down
     * together with the verdict, and `why` names the **first** one that was
     * true, in the order the decision itself evaluates them.
     *
     * ## Why consecutive identical evaluations are dropped
     *
     * `applyVisibility` runs on every system broadcast and every nudge, and
     * most of those change nothing. Recording all of them would bury the two
     * lines that matter under several hundred identical ones, and a log nobody
     * can scan is a log nobody reads. A **change** is the unit of interest,
     * which is also what the owner asked for.
     */
    private fun traceVisibility(
        hidden: Boolean,
        screenOff: Boolean,
        quiet: Boolean,
        inForeground: Boolean,
        asleep: Long,
    ) {
        val why = when {
            !hidden -> "visible"
            screenOff -> "screenOff"
            quiet -> "paymentQuiet"
            inForeground -> "swipInForeground"
            else -> "snoozed"
        }
        val key = "$hidden/$why"
        if (key == lastTrace) return
        lastTrace = key

        BubbleTrace.log(
            this, "visibility",
            "visible" to !hidden,
            "why" to why,
            "screenOff" to screenOff,
            "paymentQuiet" to quiet,
            "swipInForeground" to inForeground,
            "snoozedForMs" to
                (if (asleep > 0L) asleep - System.currentTimeMillis() else 0L),
            "running" to running,
            "attached" to (bubble != null),
        )
    }

    /** Last `hidden/why` pair written, so an unchanged decision is not repeated. */
    private var lastTrace: String? = null

    /**
     * `F-170`. Appear by **popping in**, disappear instantly.
     *
     * > *"as seamless as the messenger bubble icon that comes and pops up"*
     *
     * The bubble spends most of its life hidden — behind a payment, behind
     * SWIP itself, behind a snoozed afternoon — so the moment it comes back is
     * the moment the user actually sees, and it used to be a hard cut from
     * nothing to a full-size circle. That cut is why it read as an overlay
     * pasted on the screen rather than something arriving on it.
     *
     * Springing up from 60% with `DAMPING_RATIO_MEDIUM_BOUNCY` is the chat
     * head's entrance, and it costs nothing: the same two scale springs the
     * press uses, aimed somewhere else.
     *
     * **Going away is not animated, deliberately.** Three of the four reasons
     * to hide are the screen turning off, a payment app coming forward and
     * SWIP itself coming forward — all of which mean something else is already
     * taking the screen, and animating out under it would draw the eye to a
     * bubble that is supposed to be getting out of the way. The fourth, the
     * long-press snooze, said its own goodbye before this ran (`F-185` replaced
     * that with the swallow animation and a toast).
     *
     * [wasVisible] rather than reading `view.visibility`: this method is
     * called on every broadcast and every nudge, many of which change nothing,
     * and re-popping a bubble that was already on screen would make it twitch
     * every time the user unlocked their phone.
     */
    private fun show(visible: Boolean) {
        val view = bubble ?: return

        // Checked before the no-op guard below, and `wasVisible` deliberately
        // left alone: this call has not been honoured, so the next one still
        // has to find a state that says "on screen, wants to be off".
        if (!visible) {
            val left = goodbyeUntil - System.currentTimeMillis()
            if (left > 0L) {
                main.removeCallbacks(unquiet)
                main.postDelayed(unquiet, left + 50L)
                return
            }
        }

        if (visible == wasVisible && view.visibility != View.GONE) return
        wasVisible = visible

        if (!visible) {
            cancelMotion()
            // `F-185`. The fan lives in its own windows, so hiding the bubble
            // does not hide them — they would be left floating over the app
            // with the thing that owns them gone. Every reason to hide is also
            // a reason the menu is stale: the screen went off, a payment
            // started, SWIP came forward, or it was snoozed.
            closeFan()
            view.visibility = View.GONE
            return
        }

        // `F-180`. Put it back before it is drawn, not after.
        //
        // The only way the window can be somewhere it should not be is a
        // swallow, which parks it over the snooze target and hides it there.
        // Restoring while `visibility` is still `GONE` means the bubble is
        // simply *at* its old place on the frame it reappears, with nothing to
        // animate — a spring here would start at bottom-centre and fly across
        // the screen in full view, which is a more elaborate version of the
        // same bug.
        if (swallowed) {
            swallowed = false
            restorePark(view)
        }

        view.visibility = View.VISIBLE
        // Set directly, not sprung: this is the *start* of the pop, and a
        // spring cannot be told where to begin — only where to end. Cancelling
        // first because writing a property a running animation owns is
        // undefined, and the press spring may still be settling from the tap
        // that hid it.
        runCatching { popX?.cancel(); popY?.cancel() }
        view.scaleX = 0.6f
        view.scaleY = 0.6f
        scaleTo(1f)
    }

    // ── the bubble itself ───────────────────────────────────────────────────

    /**
     * `F-158`. The shape is taken from the assistant overlay in the owner's
     * PDF (pages 22-24): a small circle parked against the screen edge that
     * **expands into a pill** when it has something to say, then settles back.
     *
     * ## Why a horizontal `LinearLayout` and not a `FrameLayout`
     *
     * Because the circle and the pill have to be **the same view at two
     * widths**, and that only works if the width is measured rather than set.
     * The window is `WRAP_CONTENT`; a 38 dp disc between two 9 dp pads
     * measures to exactly the 56 dp minimum, so it is a circle. Show the
     * label and the same measure pass makes it a pill. Nothing computes a
     * width, nothing animates one, and there is no state that can disagree
     * with what is on screen.
     *
     * A `FrameLayout` stacks its children, so the label would have been drawn
     * **on top of** the glyph inside an unchanged circle. That was the first
     * version of this method and it would have shipped as a smudge.
     *
     * ## The size, and the one number that has to move with it
     *
     * `F-170` — *"can you make sure that you increase the size a bit"*. 48 dp
     * to **56 dp**, which is Material's FAB diameter: the size Android itself
     * uses for a round thing that floats over content and is pressed with a
     * thumb. Messenger's chat head is about the same. 48 dp is the *minimum*
     * touch target — correct as a floor, too small for the one control that
     * has to be findable over somebody else's app.
     *
     * **The corner radius in `swip_bubble_bg.xml` is half of [size] and has to
     * be changed with it.** That is what makes the square case a true circle;
     * left at 24 dp on a 56 dp bubble it would be a rounded square, and
     * nothing would fail — it would just quietly stop being round.
     *
     * Built in code rather than inflated from a layout because it is one row
     * with two children, and a layout file for that is a second place to keep
     * in sync for no benefit.
     */
    @SuppressLint("ClickableViewAccessibility")
    private fun buildBubble(): View {
        val size = dp(56f)
        val disc = dp(38f)
        val pad = (size - disc) / 2

        val glyph = ImageView(this).apply {
            // Page 23: the mark is not painted onto the pill, it sits in its
            // own contrasting disc at the leading end. That is what keeps it
            // readable while the pill is widening, and what stops the
            // collapsed circle reading as a glyph lost in empty space.
            setBackgroundResource(R.drawable.swip_bubble_disc)
            setImageResource(R.drawable.swip_bubble_mark)
            // Inset within the disc. `ImageView` fits the drawable into the
            // padded content box, so this is what sizes the slash rather than
            // a second dimension to keep in sync.
            setPadding(dp(7f), dp(7f), dp(7f), dp(7f))
            layoutParams = LinearLayout.LayoutParams(disc, disc)
        }
        this.glyph = glyph

        // `F-185`. **No label TextView any more.**
        //
        // It existed so the bubble could stretch into a pill and say
        // something, and the only thing it ever said was *Scanning…* on a tap.
        // The owner's instruction is explicit — *"it should be circle only not
        // become rounded rectangle"* — and the fan does the acknowledging now,
        // so the pill has no remaining job.
        //
        // Deleting it takes `peek`, `reanchor` and the `label` field with it,
        // and lets `swip_bubble_bg` become a true oval: a circle by
        // construction rather than by keeping two numbers in agreement.

        return LinearLayout(this).apply {
            orientation = LinearLayout.HORIZONTAL
            gravity = Gravity.CENTER_VERTICAL
            // See the size note above: 56 dp, Material's FAB diameter, not
            // the 48 dp minimum touch target. This is pressed one-handed, at
            // a counter, usually in a hurry, over an app SWIP did not draw.
            minimumWidth = size
            minimumHeight = size
            setPadding(pad, pad, pad, pad)
            setBackgroundResource(R.drawable.swip_bubble_bg)
            // 84% rather than opaque: present without being a hole punched in
            // whatever the user is reading. `docs/32` §4 - "always there,
            // never in the way".
            alpha = 0.84f
            addView(glyph)
            // `isClickable` + the `performClick` call in the listener are what
            // make this reachable by TalkBack. A bare `setOnTouchListener` on
            // a non-clickable view is invisible to every accessibility
            // service, which for a floating button is the whole feature gone.
            isClickable = true
            setOnTouchListener(DragAndTap())
            contentDescription = getString(R.string.swip_bubble_description)
            // Hidden until `applyVisibility` has had its say. Added visible,
            // there is a frame where a bubble that should be suppressed — mid
            // payment, screen off, snoozed — is drawn at full size before
            // being taken away again.
            visibility = View.GONE
        }
    }

    /**
     * Drag, edge-snap, and tap — in one listener, because Android delivers
     * them through the same stream of events and separating them means
     * guessing which one a gesture was going to be before it is finished.
     */
    private inner class DragAndTap : View.OnTouchListener {
        private var downX = 0f
        private var downY = 0f
        private var startX = 0
        private var startY = 0
        private var downAt = 0L

        /**
         * `F-184`. The bubble's Y at touch-down, so a drag that ends in a
         * snooze can be undone.
         *
         * ## The bug this fixes, read out of the owner's own trace
         *
         * `F-180` records the resting position from `ACTION_MOVE`, so it
         * follows the finger — including the last few centimetres onto the
         * snooze target. The gesture that says *"put this away"* was therefore
         * also the gesture that said *"and remember this is where it lives"*,
         * and the bubble came back ten minutes later just above the bottom of
         * the screen.
         *
         * Two `bubble.restored` lines in that file, `y=1768` and `y=1753`, on a
         * screen 2229 px tall whose target sits at 1770. `F-180` fixed the X
         * and left the Y saying the same wrong thing more quietly.
         */
        private var preDragY = 0
        private var dragging = false

        private val slop by lazy {
            android.view.ViewConfiguration.get(this@SwipBubbleService)
                .scaledTouchSlop
        }

        /**
         * `F-170`. How fast the finger was moving when it let go.
         *
         * This is the single value that turns the snap from an animation into
         * a throw, and there is no other way to get it — `MotionEvent` carries
         * a position, never a speed. `VelocityTracker` is Android's own
         * least-squares fit over the recent history of the gesture, which is
         * why it is fed every event rather than just the last two: a
         * two-sample difference is dominated by whatever jitter the digitiser
         * produced in the final 8 ms.
         *
         * Nullable and recycled on every lift because the tracker comes from a
         * system pool. Holding one past the gesture leaks a pooled object;
         * failing to recycle it means the next gesture gets a fresh allocation
         * instead of the pooled one.
         */
        private var speed: VelocityTracker? = null

        /**
         * Above this, the *direction of the throw* picks the edge; below it,
         * the nearer edge wins.
         *
         * This is the difference between a bubble and a slider. Flick left
         * from the right-hand half of the screen and a midpoint rule sends it
         * back to the right — the gesture is ignored and it feels like the
         * bubble is fighting you. Messenger does not do that, and neither does
         * any of the chat-head implementations that were looked at.
         *
         * `scaledMinimumFlingVelocity` rather than a number of my own, because
         * it is the same threshold every list in Android uses to decide a
         * flick happened, and it is adjusted per device density.
         */
        private val flingFloor by lazy {
            android.view.ViewConfiguration.get(this@SwipBubbleService)
                .scaledMinimumFlingVelocity.toFloat()
        }

        override fun onTouch(view: View, event: MotionEvent): Boolean {
            val lp = params ?: return false

            when (event.actionMasked) {
                MotionEvent.ACTION_DOWN -> {
                    // `F-170`. The finger outranks the physics. Without this
                    // a bubble grabbed while it is still flying keeps being
                    // pulled towards the edge it was thrown at, and drags with
                    // a ghost tugging at it — the exact opposite of the direct
                    // manipulation this change is for.
                    cancelMotion()

                    downX = event.rawX
                    downY = event.rawY
                    startX = lp.x
                    startY = lp.y
                    // `F-184`. Where the bubble was **before this gesture**,
                    // kept separately from [startY] because [startY] is the
                    // drag's origin and this is the snooze's undo point. They
                    // are the same number and they mean different things, and
                    // the day one of them moves the other must not follow.
                    preDragY = lp.y
                    downAt = System.currentTimeMillis()
                    dragging = false

                    speed?.recycle()
                    speed = VelocityTracker.obtain().apply { addMovement(event) }

                    // `F-173`. **No long-press timer here any more.**
                    //
                    // There used to be one, posted on this line, which snoozed
                    // the bubble if the finger stayed still. It is gone, and
                    // the deletion is the fix rather than a side effect: a
                    // timer that fires under a finger which may still be about
                    // to drag has to guess what the gesture will become, and
                    // when it guessed wrong it ran a text peek, a re-anchor
                    // spring and a scale kick on a view whose press spring was
                    // still settling. That pile-up is what the owner saw as
                    // *"on holding the launcher icon it glitches"*.
                    //
                    // Snoozing is a drag onto a target now. A drag cannot be
                    // mistaken for anything else, because by the time the
                    // target appears the gesture has already declared itself.

                    // Sprung rather than `animate().setDuration(120)`, for the
                    // reason in the physics section: a tap shorter than 120 ms
                    // used to release before the press had finished shrinking,
                    // so the two fixed animations fought and the bubble
                    // visibly hitched under a quick tap. A spring handed a new
                    // target keeps its velocity and simply turns round.
                    scaleTo(0.88f)
                    return true
                }

                MotionEvent.ACTION_MOVE -> {
                    speed?.addMovement(event)
                    val dx = event.rawX - downX
                    val dy = event.rawY - downY
                    if (!dragging && (abs(dx) > slop || abs(dy) > slop)) {
                        dragging = true
                        BubbleTrace.log(this@SwipBubbleService, "drag.start")
                        // `F-185`. A fan left open while its bubble walks off
                        // is two discs pointing at nothing. Closed here rather
                        // than on `ACTION_DOWN`, because a press that turns out
                        // to be a tap must not have dismissed it on the way in.
                        closeFan()
                        // `F-173`. The target appears the moment the gesture
                        // becomes a drag — not on touch-down, or a tap would
                        // flash a snooze target for one frame every time
                        // somebody opened the scanner.
                        showTarget()
                    }
                    if (dragging) {
                        lp.x = startX + dx.toInt()
                        lp.y = startY + dy.toInt()
                        // `F-180`. The drag writes the params directly rather
                        // than through [windowY], so the recorder there never
                        // sees it. Without this line a drag that ends exactly
                        // where it started animates nothing, so no spring
                        // frame runs, and the remembered position is the one
                        // from before the drag.
                        if (!swallowed) restY = lp.y
                        runCatching { windows.updateViewLayout(view, lp) }
                        updateTarget(view, lp)
                    }
                    return true
                }

                MotionEvent.ACTION_UP, MotionEvent.ACTION_CANCEL -> {
                    // Whether this ends in a snooze or not, the target goes.
                    // Ordered first so an early `return` further down cannot
                    // leave an overlay window on screen with nothing dragging.
                    val snoozing = dragging && targetArmed &&
                        event.actionMasked == MotionEvent.ACTION_UP
                    // Read before `hideTarget` nulls it. See [swallow].
                    val centre = targetParams?.let {
                        (it.x + targetSize / 2) to (it.y + targetSize / 2)
                    }
                    hideTarget()

                    if (!snoozing) scaleTo(1f)

                    // 1000 units of time = pixels per second, which is what
                    // `SpringAnimation` and `FlingAnimation` both expect. The
                    // default is pixels per millisecond and would make every
                    // throw a thousand times too slow to see.
                    val tracker = speed
                    tracker?.addMovement(event)
                    tracker?.computeCurrentVelocity(1000)
                    val vx = tracker?.xVelocity ?: 0f
                    val vy = tracker?.yVelocity ?: 0f
                    tracker?.recycle()
                    speed = null

                    if (snoozing) {
                        BubbleTrace.log(this@SwipBubbleService, "drag.snoozed")
                        swallow(view, centre, preDragY)
                    } else if (dragging) {
                        snapToEdge(view, lp, vx, vy)
                    } else if (event.actionMasked == MotionEvent.ACTION_UP) {
                        // A tap. `ViewConfiguration`'s long-press timeout is
                        // the right boundary: anything longer was somebody
                        // holding it, probably about to drag, and opening a
                        // scanner under their finger would be a surprise.
                        val held = System.currentTimeMillis() - downAt
                        if (held < android.view.ViewConfiguration
                                .getLongPressTimeout()) {
                            // `performClick` before the work, so an
                            // accessibility service hears the click it is
                            // waiting for. Without it the bubble is a button
                            // TalkBack cannot press.
                            view.performClick()
                            // `F-185`. The fan, not the scanner. The bubble
                            // has two vectors behind it and used to offer one.
                            toggleFan()
                        }
                    }
                    return true
                }
            }
            return false
        }

        /**
         * `F-170`. Let go, and the bubble carries on doing what the finger
         * was doing — then lands.
         *
         * The old version of this method was four lines of `ValueAnimator`
         * with `duration = 260` and an `OvershootInterpolator`, and it ignored
         * the gesture entirely: where the finger was when it lifted was the
         * only input. This one takes the velocity as well, and the two axes
         * get different treatment because they are different problems.
         *
         * ## X is a spring, because there is somewhere to land
         *
         * Horizontally the bubble has exactly two rest positions — the left
         * margin and the right one. That is a spring: a fixed target, a start
         * velocity, and no duration at all. Thrown hard it arrives fast and
         * overshoots a little into the edge; nudged, it drifts across. Same
         * code, and the difference is the throw rather than a branch.
         *
         * ## Y is a fling, because there is nowhere to land
         *
         * Vertically every position is equally valid, so there is no target to
         * spring to — what should happen is that the bubble keeps travelling
         * and slows down, which is precisely what `FlingAnimation` is. Bounded
         * by `setMinValue`/`setMaxValue` so it stops at the edges of the
         * allowed strip instead of sailing off the top, which is a bubble the
         * user has to reboot to get back.
         *
         * Friction 1.1 rather than the default 1.0: slightly stickier than a
         * scrolling list, because a bubble that keeps gliding for a second
         * after you let go feels out of control when it is sitting on top of
         * somebody else's app.
         *
         * ## Why the throw direction can beat the midpoint
         *
         * See [flingFloor]. Below it, the nearer edge wins, which is what you
         * want when someone has carefully placed the bubble. Above it, the
         * direction of the throw wins, which is what you want when someone has
         * flicked it — and a midpoint rule in that case sends the bubble back
         * where it came from, which reads as the app refusing the gesture.
         */
        private fun snapToEdge(
            view: View,
            lp: WindowManager.LayoutParams,
            vx: Float,
            vy: Float,
        ) {
            val screenWidth = resources.displayMetrics.widthPixels
            val margin = dp(8f)

            parkedRight = if (abs(vx) > flingFloor) {
                vx > 0f
            } else {
                lp.x + view.width / 2 >= screenWidth / 2
            }
            val target = edgeX(view).toFloat()

            // Keep it on screen vertically too — a bubble dragged off the top
            // is a bubble the user has to reboot to get back. Both bounds come
            // from [lowestY] so this and [restorePark] cannot disagree.
            val lowest = lowestY(view)

            slideX?.apply {
                cancel()
                setStartVelocity(vx)
                // `F-186`. A tick when the bubble actually reaches the edge.
                //
                // > *"can you add haptic feedback for the bubbles? Whenever I
                // > move it to either of the ends, it creates haptic feedback"*
                //
                // On the spring's **end listener**, not at the moment of
                // release. Buzzing on release would be feedback about the
                // finger, which the finger already knows; buzzing on arrival
                // is feedback about the bubble, which is off under the thumb
                // and is the thing there is no other way to feel.
                //
                // `addEndListener` rather than a `postDelayed` guess: a spring
                // has no duration, so there is no number to guess. The
                // listener is added fresh each snap and removed by the
                // animation when it ends, so they do not accumulate.
                //
                // Written as a SAM conversion held in a `var` rather than as
                // an anonymous `object`: the listener's Java signature takes a
                // **raw** `DynamicAnimation`, and spelling that out in Kotlin
                // is a guess at a generic bound. The lambda lets the compiler
                // work it out, and the self-reference is what allows the
                // listener to take itself off again.
                var tick: DynamicAnimation.OnAnimationEndListener? = null
                tick = DynamicAnimation.OnAnimationEndListener { a, canceled, _, _ ->
                    a.removeEndListener(tick)
                    // Not on cancel: a cancelled snap is a bubble the user
                    // grabbed again mid-flight, and it never landed.
                    if (!canceled) {
                        runCatching {
                            view.performHapticFeedback(
                                HapticFeedbackConstants.CLOCK_TICK)
                        }
                    }
                }
                addEndListener(tick)
                animateToFinalPosition(target)
            }

            if (lp.y in margin..lowest && abs(vy) > flingFloor) {
                // Started inside the strip and thrown: glide, and let friction
                // decide where it stops.
                glideY = FlingAnimation(view, windowY).apply {
                    setStartVelocity(vy)
                    // `setFriction`, not `friction =` — see `springFor`.
                    setFriction(1.1f)
                    setMinValue(margin.toFloat())
                    setMaxValue(lowest.toFloat())
                    start()
                }
            } else {
                // Either barely moving, or already outside the strip because
                // the finger dragged it there. Both want the same thing: come
                // to rest at the nearest legal position, without a bounce —
                // `DAMPING_RATIO_NO_BOUNCY`, set in `buildPhysics`.
                //
                // A fling would be wrong here: `FlingAnimation` with a start
                // position outside its own min/max ends immediately, leaving
                // the bubble stranded off screen.
                settleY?.apply {
                    cancel()
                    setStartVelocity(vy)
                    animateToFinalPosition(
                        lp.y.coerceIn(margin, lowest).toFloat()
                    )
                }
            }
        }
    }

    /**
     * `F-163`. Open the scanner **over** whatever the user is in.
     *
     * This used to launch `MainActivity` with `SwipTile.EXTRA_OPEN_SCANNER`,
     * which opened the whole of SWIP full-screen — so tapping the floating
     * button took you out of the app you were standing in, which is the one
     * thing a floating button exists to avoid.
     *
     * It now opens [SwipHoverActivity]: a transparent Activity in its own
     * task, drawing a card with `ScanPage` in it over the app underneath. Same
     * camera, same detection, same resolver, same ledger — because it is the
     * same widget, not a second implementation of one.
     *
     * The Quick Settings tile still opens `MainActivity`, and should: a tile
     * press happens from the shade with nothing behind it to hover over.
     */
    private fun openScanner() {
        BubbleTrace.log(this, "tap.openScanner")

        // `F-185`. **No `peek()` here any more.**
        //
        // It used to expand the bubble into a pill reading *Scanning…* to
        // cover the half second the hovering window takes to start its engine.
        // Two things wrong with that, and the owner caught both: the pill is
        // what turned the circle into a rounded rectangle, and nothing was
        // scanning — the camera was still half a second away.
        //
        // The fan covers the same half second honestly. By the time this runs
        // the user has already pressed twice, and a menu closing is its own
        // acknowledgement.

        val launch = Intent(this, SwipHoverActivity::class.java).apply {
            // NEW_TASK is required to start an Activity from a Service at all.
            // CLEAR_TOP rather than REORDER_TO_FRONT so a second tap restarts
            // the scanner cleanly instead of resurfacing a card whose camera
            // has already been released.
            addFlags(
                Intent.FLAG_ACTIVITY_NEW_TASK or
                    Intent.FLAG_ACTIVITY_CLEAR_TOP
            )
            // Flutter's own extra. `main()` branches on it: without this the
            // engine would come up as the entire app inside a transparent
            // window, which looks like SWIP has been pasted over the screen.
            putExtra(
                SwipHoverActivity.EXTRA_ROUTE,
                SwipHoverActivity.ROUTE_HOVER,
            )
        }

        runCatching { startActivity(launch) }
    }

    /**
     * `F-180`. The three numbers that define a legal resting place, in one
     * place, because three copies of them is how they drift.
     *
     * [snapToEdge] and [restorePark] both have to agree on where
     * the bubble is allowed to sit, and they used to compute it separately.
     * That is survivable while two of them run one after the other and
     * invisible when the third runs ten minutes later — which is exactly the
     * shape of the bug this round fixed.
     */
    private fun edgeX(view: View): Int = BubblePark.edgeX(
        parkedRight,
        resources.displayMetrics.widthPixels,
        view.width,
        dp(8f),
    )

    /**
     * The lowest Y the bubble may rest at.
     *
     * `coerceAtLeast` before any range is built from it: on a short display
     * this subtraction can land under the margin, and `coerceIn` **throws**
     * when its maximum is below its minimum — inside a touch handler, on a
     * window the user has no way to dismiss.
     */
    private fun lowestY(view: View): Int = BubblePark.lowestY(
        resources.displayMetrics.heightPixels,
        view.height,
        dp(8f),
        dp(72f),
    )

    /**
     * `F-180`. Put the window back where the user left it.
     *
     * Assigned rather than sprung, and called only from [show] while the
     * window is still `GONE` — see the comment there. [restY] is null only
     * before the bubble has ever settled, in which case the fallback is the
     * same third-of-the-screen [addBubble] starts at, so a snooze taken before
     * the first drag returns it to where it began rather than to zero.
     */
    private fun restorePark(view: View) {
        val lp = params ?: return
        lp.x = edgeX(view)
        lp.y = BubblePark.restY(
            restY,
            resources.displayMetrics.heightPixels,
            view.height,
            dp(8f),
            dp(72f),
        )
        // Any spring still holding the swallow's end position would overwrite
        // this on its next frame. They are already cancelled by `show(false)`
        // via `cancelMotion`, but this method must be correct on its own —
        // it is the last thing between a fixed bug and a returning one.
        runCatching { slideX?.cancel(); settleY?.cancel(); glideY?.cancel() }
        runCatching { windows.updateViewLayout(view, lp) }
        BubbleTrace.log(this, "bubble.restored", "x" to lp.x, "y" to lp.y)
    }

    // ── the notification Android requires ───────────────────────────────────

    /**
     * A foreground service is the price of an overlay that survives the user
     * leaving SWIP, and the notification is the honest part of that price:
     * there is no way to draw over other apps *quietly*, and there should not
     * be.
     *
     * `IMPORTANCE_MIN` so it never makes a sound, never peeks, and sits at the
     * bottom of the shade.
     */
    private fun startInForeground() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            val manager = getSystemService(NotificationManager::class.java)
            manager.createNotificationChannel(
                NotificationChannel(
                    CHANNEL_ID,
                    getString(R.string.swip_bubble_channel),
                    NotificationManager.IMPORTANCE_MIN,
                ).apply {
                    description = getString(R.string.swip_bubble_channel_note)
                    setShowBadge(false)
                }
            )
        }

        val open = PendingIntent.getActivity(
            this,
            0,
            Intent(this, MainActivity::class.java)
                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK),
            PendingIntent.FLAG_IMMUTABLE,
        )

        val stop = PendingIntent.getService(
            this,
            1,
            Intent(this, SwipBubbleService::class.java)
                .setAction(ACTION_STOP),
            PendingIntent.FLAG_IMMUTABLE,
        )

        // `F-167`. The discoverable half of snooze. Long-pressing the bubble
        // is faster, but nobody discovers a long-press; a labelled button in
        // the shade is how people find out the gesture exists at all.
        val snooze = PendingIntent.getService(
            this,
            2,
            Intent(this, SwipBubbleService::class.java)
                .setAction(ACTION_SNOOZE_HOUR),
            PendingIntent.FLAG_IMMUTABLE,
        )

        @Suppress("DEPRECATION")
        val builder = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            Notification.Builder(this, CHANNEL_ID)
        } else {
            // The channel overload is API 26. Below it there are no channels
            // at all, and the one-argument constructor is the only form.
            Notification.Builder(this)
        }

        val notification: Notification =
            builder
                .setSmallIcon(R.drawable.swip_bubble_mark)
                .setContentTitle(getString(R.string.swip_bubble_running))
                .setContentText(getString(R.string.swip_bubble_running_note))
                .setContentIntent(open)
                .addAction(
                    Notification.Action.Builder(
                        null as android.graphics.drawable.Icon?,
                        getString(R.string.swip_bubble_snooze_hour),
                        snooze,
                    ).build()
                )
                .addAction(
                    Notification.Action.Builder(
                        // Explicitly the `Icon?` overload. `Action.Builder`
                        // also has a deprecated `(int, ...)` form, and a bare
                        // `null` resolving to the right one is an accident
                        // waiting for a toolchain bump.
                        null as android.graphics.drawable.Icon?,
                        getString(R.string.swip_bubble_turn_off),
                        stop,
                    ).build()
                )
                .setOngoing(true)
                .build()

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
            // Android 14 demands a type. SPECIAL_USE is the correct one — the
            // bubble is not a media player, a location tracker or a sync. The
            // manifest carries the matching declaration and the justification
            // string a reviewer will read.
            startForeground(
                NOTIFICATION_ID,
                notification,
                ServiceInfo.FOREGROUND_SERVICE_TYPE_SPECIAL_USE,
            )
        } else {
            startForeground(NOTIFICATION_ID, notification)
        }
    }
