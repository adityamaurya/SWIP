/**
 * `F-158` — **the floating bubble. It exists now.**
 *
 * > *"the floater launcher icon is not working"*
 *
 * It was not working because **it had never been built**. `F-131` shipped the
 * permission screen — the explain-then-send-to-Settings flow that `docs/32`
 * §6 calls step 1 — and steps 2 to 6 were never started. The switch on that
 * screen wrote a `SharedPreferences` boolean that nothing on earth read. The
 * permission was granted, the toggle went on, and no bubble appeared, because
 * there was no code anywhere in the project that drew one.
 *
 * This is step 2, and it is the one that makes the feature real: a foreground
 * service holding a `TYPE_APPLICATION_OVERLAY` window, draggable, edge-snapping,
 * suppressing itself where it must, and opening SWIP's scanner on a tap.
 *
 * ## Why the camera is not inside the bubble yet
 *
 * `docs/32` §3 argues the scan window should be CameraX + ML Kit drawn in a
 * second overlay, so the whole interaction happens without leaving the app
 * you are in. That is still right and it is still the goal.
 *
 * It is not in this commit for a concrete, checkable reason rather than a
 * vague one: **CameraX and ML Kit are Gradle dependencies, and this project's
 * `build.gradle` is generated by `flutter create` inside `tool/bootstrap.sh`
 * on every machine and in CI.** Nothing in `android/app/build.gradle` survives
 * a bootstrap, so adding a dependency there would work locally and vanish on
 * the next clean checkout. Making that possible means teaching bootstrap to
 * inject dependencies into a file it generates, which is its own change with
 * its own failure modes, and it should not ride along inside the commit that
 * first makes the bubble appear.
 *
 * So: this bubble opens SWIP's existing, tested scanner — the one that already
 * handles `noDuplicates`, the aim detector, the resolver and the ledger. One
 * app switch instead of zero. That is worse than the goal and enormously
 * better than a toggle that does nothing.
 *
 * ## The rule from `docs/32` §2, actually enforced
 *
 * > **The SWIP bubble never appears over a payment.**
 *
 * Detecting the foreground app normally needs usage-access or an
 * accessibility service, and SWIP asks for neither — so the rule is kept the
 * other way round, using only signals this service already owns:
 *
 * * hidden while the screen is off or the keyguard is up;
 * * hidden for 90 seconds after SWIP hands off a `upi://` intent, because that
 *   is exactly when a payment app is in front of the user;
 * * hidden while SWIP itself is in the foreground, because a bubble over the
 *   app's own scanner is just a smudge on the viewfinder.
 *
 * Every one of those errs towards the bubble being **absent**. An absent
 * bubble costs one extra tap. A bubble over a PIN pad costs the app.
 */
class SwipBubbleService : Service() {

    companion object {
        // `F-185`. The fan's three numbers. Here rather than in a second
        // `companion object` of their own — a Kotlin class may only have one,
        // and two is a compile error rather than a style opinion.

        /** Gap between the bubble's centre and the first item's centre. */
        private const val FAN_GAP_DP = 68f

        /** Each item lands this much later than the one before it. */
        private const val FAN_STAGGER_MS = 45L

        /** Long enough to read two icons, short enough not to be litter. */
        private const val FAN_TIMEOUT_MS = 6_000L

        private const val CHANNEL_ID = "swip.bubble"
        private const val NOTIFICATION_ID = 0x5117

        /** Start it. Idempotent — a second start just re-shows the bubble. */
        const val ACTION_START = "in.swip.app.BUBBLE_START"
        const val ACTION_STOP = "in.swip.app.BUBBLE_STOP"

        /**
         * "Something changed, look again." Carries no information itself —
         * everything it might have carried is in the shared state below,
         * which is the whole point.
         */
        const val ACTION_RE_EVALUATE = "in.swip.app.BUBBLE_LOOK_AGAIN"

        /** `docs/32` §2. Long enough to cover a checkout, short enough to come back. */
        private const val PAYMENT_QUIET_MS = 90_000L

        /** Whether the service is up. Read over the method channel. */
        @Volatile
        var running: Boolean = false
            private set

        // ── one source of truth for "should the bubble be there" ─────────
        //
        // `F-131` kept this in Flutter's `SharedPreferences` under
        // `swip.bubble.enabled`, and that was half the reason the feature
        // looked broken: Dart owned a boolean, Android owned the actual
        // window, and nothing reconciled them. The notification's "Turn off"
        // action makes that split unworkable - it stops the service from a
        // process Dart may not even be running in, and the Settings toggle
        // would still have shown "on" the next time the app opened.
        //
        // So the service owns it, in its own file, and Dart ASKS. There is
        // exactly one place the answer lives and it is the same place the
        // window lives.

        private const val PREFS = "swip.bubble"
        private const val KEY_WANTED = "wanted"

        /**
         * `F-167` — when the bubble is asleep until.
         *
         * Wispr Flow lets you flick the bubble away for the day, and `docs/32`
         * once promised the same. `F-159` **deleted that promise** rather than
         * leave it unkept. This is it, kept.
         *
         * Stored rather than held in memory, because the two things that most
         * want to end a snooze early — the process dying, or the phone
         * restarting — are exactly the two that a field in memory would not
         * survive. A snooze that quietly ends when Android reclaims the
         * process is not a snooze.
         */
        private const val KEY_SNOOZE_UNTIL = "snoozeUntil"

        /** An hour, from the notification. */
        const val ACTION_SNOOZE_HOUR = "in.swip.app.BUBBLE_SNOOZE_HOUR"

        private const val ONE_HOUR_MS = 60L * 60L * 1000L

        /**
         * `F-173`. **Ten minutes, and the number came from the owner's own
         * reference.**
         *
         * > *"in similar way in the screenshot of wispr flow it should snooze
         * > for 10mins by default"*
         *
         * It replaces "until tomorrow", and the change is bigger than the
         * duration. A snooze until tomorrow has to be *undone* — there is no
         * gesture that means "actually, come back", so the only way out was to
         * open SWIP and find a switch. Ten minutes ends by itself, which is
         * what makes it safe to offer as a one-handed drag rather than
         * something you have to be sure about.
         */
        const val SNOOZE_DEFAULT_MS = 10L * 60L * 1000L

        /**
         * How long the bubble stays on screen after being snoozed, so the
         * message explaining where it went can be read.
         *
         * Longer than the old pill's 900 ms settle would be pointless — it
         * has collapsed back to a circle by then and there is nothing left to
         * read. Shorter and the sentence is gone before the eye reaches it.
         */
        private const val GOODBYE_MS = 900L

        /**
         * `F-173`. How long the bubble is kept on screen while it is being
         * pulled into the snooze target and shrunk away.
         *
         * Shorter than [GOODBYE_MS] because there is nothing to *read* — the
         * animation is the message, and an animation that lingers after it has
         * finished reads as lag.
         */
        private const val SWALLOW_MS = 420L

        /**
         * `SYSTEM_ALERT_WINDOW` became a special, user-granted permission in
         * API 23. Below that it is an ordinary install-time grant, so it is
         * already held and `canDrawOverlays` does not exist to ask.
         * `MainActivity`'s `canDrawOverlays` handler answers the same way, and
         * the two must not disagree - a Settings screen showing "allowed"
         * while the service refuses to start is the shape of bug this whole
         * round is about.
         */
        private fun canOverlay(context: Context): Boolean =
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
                Settings.canDrawOverlays(context)
            } else {
                true
            }

        private fun prefs(context: Context): SharedPreferences =
            context.applicationContext
                .getSharedPreferences(PREFS, Context.MODE_PRIVATE)

        /** What the user last asked for, regardless of what is on screen. */
        fun isWanted(context: Context): Boolean =
            prefs(context).getBoolean(KEY_WANTED, false)

        /** Epoch millis the snooze ends at, or 0. Past values read as awake. */
        fun snoozedUntil(context: Context): Long {
            val until = prefs(context).getLong(KEY_SNOOZE_UNTIL, 0L)
            return if (until > System.currentTimeMillis()) until else 0L
        }

        /**
         * Put the bubble to sleep until [until] (epoch millis).
         *
         * Deliberately does **not** clear `KEY_WANTED`. Snoozing and switching
         * off are different intentions: one says "not right now", the other
         * says "not at all", and collapsing them would mean a flick to get the
         * button out of the way silently undid the setup that put it there.
         */
        fun snooze(context: Context, until: Long, from: String = "?") {
            BubbleTrace.log(context, "snooze.set",
                "forMs" to (until - System.currentTimeMillis()), "from" to from)
            prefs(context).edit().putLong(KEY_SNOOZE_UNTIL, until).apply()
            nudge(context)
        }

        /**
         * `F-173`. The drag-to-target snooze: ten minutes, shake to end it.
         *
         * This replaces `snoozeForTheDay`, which is deleted rather than kept
         * alongside. Two snooze lengths reachable by two gestures on the same
         * button is a thing to explain, and the long one had no way back
         * except opening the app — see [SNOOZE_DEFAULT_MS].
         */
        fun snoozeBriefly(context: Context) {
            snooze(context, System.currentTimeMillis() + SNOOZE_DEFAULT_MS,
                from = "dragTarget")
        }

        /** Bring it back now. */
        fun wake(context: Context, from: String = "?") {
            BubbleTrace.log(context, "snooze.end", "from" to from)
            prefs(context).edit().remove(KEY_SNOOZE_UNTIL).apply()
            nudge(context)
        }

        /**
         * Turn the bubble on. Returns false - and changes nothing - if the
         * overlay permission is not granted, because recording a wish that
         * cannot be honoured is how the old toggle lied.
         */
        fun start(context: Context): Boolean {
            if (!canOverlay(context)) {
                BubbleTrace.log(context, "start.refused", "reason" to "noOverlayPermission")
                return false
            }
            BubbleTrace.log(context, "start.wanted")
            prefs(context).edit().putBoolean(KEY_WANTED, true).apply()
            val intent = Intent(context, SwipBubbleService::class.java)
                .setAction(ACTION_START)
            // A foreground service cannot be started from the background on
            // Android 12+, so every caller of this is a foregrounded
            // Activity. `runCatching` is the belt for the case where it is
            // not: a ForegroundServiceStartNotAllowedException must not take
            // the app down over a convenience feature.
            return runCatching {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                    context.startForegroundService(intent)
                } else {
                    context.startService(intent)
                }
            }.isSuccess
        }

        /** Turn it off, and remember that. */
        fun stop(context: Context) {
            BubbleTrace.log(context, "stop.requested")
            prefs(context).edit().putBoolean(KEY_WANTED, false).apply()
            runCatching {
                context.stopService(Intent(context, SwipBubbleService::class.java))
            }
        }

        /**
         * Bring the bubble back if the user had it on.
         *
         * Called from [MainActivity.onCreate]. **This is deliberately not a
         * `BOOT_COMPLETED` receiver:** that needs another permission, and a
         * category reader restarting itself the moment a phone boots is a
         * worse trade than the bubble being absent until SWIP is next opened.
         * The cost is one app launch after a reboot, and it is written on the
         * Settings screen rather than left as a surprise.
         */
        fun restoreIfWanted(context: Context) {
            val wanted = isWanted(context)
            BubbleTrace.log(context, "restore.check",
                "running" to running, "wanted" to wanted)
            if (!running && wanted) start(context)
        }

        // ── why the next two are shared state and not events ─────────────
        //
        // **This is the bug that made the bubble look dead after it was
        // built.** Foreground state used to travel only as a broadcast, and
        // `signal` dropped it when the service was not yet `running`. Starting
        // a service is asynchronous: `startForegroundService` returns long
        // before `onStartCommand` runs. So the ordinary first-use sequence —
        //
        //   1. flip the switch, which starts the service
        //   2. press Home, which fires ACTION_APP_BACKGROUND
        //   3. the service reaches `onStartCommand` some time after that
        //
        // lost step 2 entirely. The service came up believing SWIP was still
        // in front, and **the bubble stayed hidden until the user happened to
        // open SWIP and leave it again.** Which reads exactly like a floating
        // button that does not work.
        //
        // An event you can miss is the wrong shape for a fact that is always
        // true or false right now. These are written by `MainActivity` and
        // **read** by `applyVisibility`, so a lost broadcast costs a moment of
        // staleness rather than a permanently wrong answer. The broadcasts
        // still exist, but only to nudge a running service to look again.

        /**
         * Whether SWIP itself is on screen.
         *
         * **Starts `false`, and the default is the interesting part.**
         *
         * The obvious default is `true`: the usual way this service starts is
         * a foregrounded `MainActivity`, since Android 12+ forbids starting a
         * foreground service from the background. But that is not the *only*
         * way. `START_STICKY` restarts it after a process death, and a
         * `BOOT_COMPLETED` receiver starts it after a reboot — and in both of
         * those there is no Activity at all, so nobody would ever correct a
         * `true` and the bubble would hide itself forever.
         *
         * `false` is wrong for at most the few milliseconds between
         * `MainActivity.onResume` and the service starting, and `onResume`
         * claims the foreground **before** it calls `restoreIfWanted`, so even
         * that window is closed.
         */
        @Volatile
        var appInForeground: Boolean = false
            private set

        /** Epoch millis until which the bubble stays out of a payment's way. */
        @Volatile
        var quietUntil: Long = 0L
            private set

        /** Called from `MainActivity.onResume` / `onPause`. */
        fun noteForeground(context: Context, inFront: Boolean, from: String = "?") {
            // `F-176`. `from` is the whole reason this event is worth
            // recording: two Activities report foreground state, they have had
            // different lifecycle hooks, and "which one said SWIP was in
            // front, and did anything ever say it had left" is exactly the
            // question a disappearing bubble raises.
            BubbleTrace.log(context, "foreground",
                "inFront" to inFront, "from" to from, "was" to appInForeground)
            appInForeground = inFront
            nudge(context)
        }

        /**
         * `docs/32` §2 — the bubble never appears over a payment.
         *
         * A timestamp rather than a flag plus a timer, so a signal that
         * arrives before the service exists is still honoured when it starts:
         * the deadline is already in the future and `applyVisibility` reads it.
         */
        fun notePaymentStarted(context: Context) {
            quietUntil = System.currentTimeMillis() + PAYMENT_QUIET_MS
            BubbleTrace.log(context, "payment.quiet", "forMs" to PAYMENT_QUIET_MS)
            nudge(context)
        }

        /**
         * Ask a running service to re-read the state above.
         *
         * Safe to lose. `setPackage` keeps it inside SWIP: the receiver is
         * registered `RECEIVER_NOT_EXPORTED`, and an un-packaged broadcast of
         * an action string this specific would still be a needless thing to
         * put on the system bus.
         */
        private fun nudge(context: Context) {
            if (!running) return
            runCatching {
                context.sendBroadcast(
                    Intent(ACTION_RE_EVALUATE).setPackage(context.packageName)
                )
            }
        }
    }

